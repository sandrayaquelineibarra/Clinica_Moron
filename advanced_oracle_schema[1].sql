-- 4. Creación de Paquete PL/SQL Avanzado (Specification & Body)
CREATE OR REPLACE PACKAGE pkg_clinica_gestion AS
    -- Procedimiento para poblar 100 pacientes con control de excepciones avanzado
    PROCEDURE sp_generar_pacientes_masivos;
    
    -- Función para consultar la carga de trabajo de un médico usando funciones analíticas
    FUNCTION fn_obtener_ranking_medicos RETURN SYS_REFCURSOR;
END pkg_clinica_gestion;
/

CREATE OR REPLACE PACKAGE BODY pkg_clinica_gestion AS

    PROCEDURE sp_generar_pacientes_masivos IS
        v_genero VARCHAR2(15);
        v_grupo VARCHAR2(5);
        v_total_insertados NUMBER := 0;
    BEGIN
        FOR i IN 1..100 LOOP
            -- Asignación condicional avanzada
            IF MOD(i, 2) = 0 THEN
                v_genero := 'Femenino';
            ELSE
                v_genero := 'Masculino';
            END IF;

            CASE MOD(i, 8)
                WHEN 0 THEN v_grupo := 'A+';
                WHEN 1 THEN v_grupo := 'A-';
                WHEN 2 THEN v_grupo := 'B+';
                WHEN 3 THEN v_grupo := 'B-';
                WHEN 4 THEN v_grupo := 'AB+';
                WHEN 5 THEN v_grupo := 'AB-';
                WHEN 6 THEN v_grupo := 'O+';
                ELSE v_grupo := 'O-';
            END CASE;

            BEGIN
                INSERT INTO pacientes (nombre, apellido, fecha_nacimiento, genero, telefono, email, direccion, grupo_sanguineo)
                VALUES (
                    'Paciente_' || i,
                    'Apellido_' || i,
                    ADD_MONTHS(SYSDATE, -12 * (18 + MOD(i, 50))),
                    v_genero,
                    '+541144' || LPAD(i, 4, '0'),
                    'paciente_' || i || '@clinica-moron.ar',
                    'Av. Rivadavia ' || (i * 15),
                    v_grupo
                );
                v_total_insertados := v_total_insertados + 1;
            EXCEPTION
                WHEN DUP_VAL_ON_INDEX THEN
                    NULL; -- Manejo elegante de duplicados si se reejecuta
                WHEN OTHERS THEN
                    RAISE_APPLICATION_ERROR(-20001, 'Error al insertar paciente ' || i || ': ' || SQLERRM);
            END;
        END LOOP;
        
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Proceso exitoso. Pacientes registrados: ' || v_total_insertados);
    END sp_generar_pacientes_masivos;

    FUNCTION fn_obtener_ranking_medicos RETURN SYS_REFCURSOR IS
        rc SYS_REFCURSOR;
    BEGIN
        -- Uso de Funciones Analíticas avanzadas de Oracle (DENSE_RANK, OVER)
        OPEN rc FOR
            SELECT 
                m.id_personal,
                m.nombre || ' ' || m.apellido AS medico,
                m.especialidad,
                COUNT(c.id_cita) AS total_citas,
                DENSE_RANK() OVER (ORDER BY COUNT(c.id_cita) DESC) AS ranking_carga
            FROM personal_medico m
            LEFT JOIN citas c ON m.id_personal = c.id_personal
            WHERE m.rol = 'medico'
            GROUP BY m.id_personal, m.nombre, m.apellido, m.especialidad;
        RETURN rc;
    END fn_obtener_ranking_medicos;

END pkg_clinica_gestion;
/

-- 5. Ejecución del procedimiento del paquete para generar los 100 pacientes
SET SERVEROUTPUT ON;
EXEC pkg_clinica_gestion.sp_generar_pacientes_masivos;

-- 6. Ejemplo de consulta avanzada utilizando funciones analíticas y CTE (Common Table Expressions)
WITH resumen_citas AS (
    SELECT 
        p.id_paciente,
        p.nombre || ' ' || p.apellido AS paciente,
        p.grupo_sanguineo,
        COUNT(c.id_cita) AS total_consultas,
        ROW_NUMBER() OVER (PARTITION BY p.genero ORDER BY p.fecha_nacimiento ASC) AS orden_etario
    FROM pacientes p
    LEFT JOIN citas c ON p.id_paciente = c.id_paciente
    GROUP BY p.id_paciente, p.nombre, p.apellido, p.grupo_sanguineo, p.genero, p.fecha_nacimiento
)
SELECT * FROM resumen_citas WHERE ROWNUM <= 15;
