-- 2. Creación de Tablas con características avanzadas de Oracle (Identidad 12c+)
CREATE TABLE personal_medico (
    id_personal NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_matricula VARCHAR2(20) UNIQUE NOT NULL,
    nombre VARCHAR2(50) NOT NULL,
    apellido VARCHAR2(50) NOT NULL,
    rol VARCHAR2(20) CONSTRAINT chk_rol CHECK (rol IN ('director', 'medico', 'enfermera', 'ayudante')) NOT NULL,
    especialidad VARCHAR2(50),
    email_institucional VARCHAR2(100) UNIQUE NOT NULL,
    fecha_ingreso DATE DEFAULT SYSDATE
);

CREATE TABLE pacientes (
    id_paciente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    apellido VARCHAR2(50) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero VARCHAR2(15) CONSTRAINT chk_genero CHECK (genero IN ('Masculino', 'Femenino', 'Otro')) NOT NULL,
    telefono VARCHAR2(20),
    email VARCHAR2(100),
    direccion VARCHAR2(150),
    grupo_sanguineo VARCHAR2(5) CONSTRAINT chk_sangre CHECK (grupo_sanguineo IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'))
);

CREATE TABLE citas (
    id_cita NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente NUMBER NOT NULL,
    id_personal NUMBER NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    estado VARCHAR2(20) DEFAULT 'programada' CONSTRAINT chk_estado CHECK (estado IN ('programada', 'completada', 'cancelada')),
    motivo_consulta CLOB,
    CONSTRAINT fk_citas_paciente FOREIGN KEY (id_paciente) REFERENCES pacientes(id_paciente) ON DELETE CASCADE,
    CONSTRAINT fk_citas_personal FOREIGN KEY (id_personal) REFERENCES personal_medico(id_personal) ON DELETE CASCADE
);

-- Índices avanzados para optimización de consultas en Oracle (B-Tree e Índices Basados en Funciones)
CREATE INDEX idx_citas_fecha ON citas(fecha_hora);
CREATE INDEX idx_pacientes_apellido ON pacientes(UPPER(apellido));

